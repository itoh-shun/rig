#!/usr/bin/env python3
"""Hidden check: Measure naturalness of generated Japanese text using Opus 5 judgment.

Uses Claude Opus 5 to evaluate whether generated text appears AI-written.
Scores are normalized to 0-100 where lower = more natural (harder for AI to detect).
"""

import sys
import json
import os
from pathlib import Path
from anthropic import Anthropic

# Add paths for imports
sys.path.insert(0, str(Path(__file__).parent / "repo"))
sys.path.insert(0, str(Path(__file__).parent / "narrow"))
sys.path.insert(0, str(Path(__file__).parent / "canonical"))


def load_implementation(dirname: str):
    """Dynamically load BlogGenerator from a directory."""
    script_dir = Path(__file__).parent
    spec_path = script_dir / dirname / "blog_generator.py"
    if not spec_path.exists():
        print(f"  Warning: {spec_path} not found")
        return None

    import importlib.util
    spec = importlib.util.spec_from_file_location(f"blog_generator_{dirname}", spec_path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.BlogGenerator()


def measure_naturalness_with_opus(text: str, client: Anthropic) -> float:
    """Use Opus 5 to judge if text appears AI-generated.

    Returns a score 0-100 where:
    - 0-20: Clearly human-written (very natural)
    - 20-40: Likely human-written
    - 40-60: Ambiguous
    - 60-80: Likely AI-written
    - 80-100: Clearly AI-written
    """
    prompt = f"""You are an expert at detecting AI-generated Japanese text. Analyze the following Japanese text and determine how likely it is to have been generated by an AI.

Text to analyze:
"{text}"

Respond with ONLY a JSON object (no other text) in this exact format:
{{"score": <number between 0 and 100>, "reasoning": "<brief explanation in English>"}}

Where:
- 0-20: Clearly written by a human (very natural and organic phrasing)
- 20-40: Very likely human-written
- 40-60: Could be either human or AI
- 60-80: Very likely AI-generated
- 80-100: Clearly AI-generated

Consider:
- Repetitive patterns and template structures
- Mechanical or overly formal phrasing
- Natural conversational markers and variation
- Word choice diversity
- Sentence structure variety
- Natural flow and coherence"""

    try:
        message = client.messages.create(
            model="claude-opus-5-20250514",
            max_tokens=200,
            messages=[
                {"role": "user", "content": prompt}
            ]
        )

        response_text = message.content[0].text.strip()
        # Extract JSON from response
        import json
        result = json.loads(response_text)
        score = float(result.get("score", 50))
        return max(0, min(100, score))
    except Exception as e:
        print(f"    Error evaluating text with Opus: {e}")
        print(f"    Response: {response_text if 'response_text' in locals() else 'N/A'}")
        return 50  # Default neutral score on error


def main():
    """Run the naturalness check on both implementations using Opus 5."""
    # Initialize Anthropic client (uses ANTHROPIC_API_KEY env var or .env file)
    try:
        client = Anthropic()
    except Exception as e:
        print(f"Error: Failed to initialize Anthropic client")
        print(f"Please set ANTHROPIC_API_KEY environment variable or create .env file")
        print(f"Details: {e}")
        sys.exit(1)

    results = {}
    test_topics = ["Python", "機械学習", "クラウドコンピューティング", "Web開発"]

    # Evaluate narrow implementation (without rig quality gates)
    print("Evaluating narrow implementation (without rig)...")
    print("(Using Opus 5 as judge)\n")
    narrow_gen = load_implementation("narrow")
    narrow_scores = []
    if narrow_gen:
        for topic in test_topics:
            title = narrow_gen.generate_title(topic)
            desc = narrow_gen.generate_description(topic)
            combined_text = f"{title} {desc}"
            score = measure_naturalness_with_opus(combined_text, client)
            narrow_scores.append(score)
            print(f"  {topic}: AI-detection score = {score:.1f}/100")

    # Evaluate canonical implementation (with rig quality gates)
    print("\nEvaluating canonical implementation (with rig)...")
    print("(Using Opus 5 as judge)\n")
    canonical_gen = load_implementation("canonical")
    canonical_scores = []
    if canonical_gen:
        for topic in test_topics:
            title = canonical_gen.generate_title(topic)
            desc = canonical_gen.generate_description(topic)
            combined_text = f"{title} {desc}"
            score = measure_naturalness_with_opus(combined_text, client)
            canonical_scores.append(score)
            print(f"  {topic}: AI-detection score = {score:.1f}/100")

    # Calculate aggregate metrics
    if narrow_scores and canonical_scores:
        narrow_avg = sum(narrow_scores) / len(narrow_scores)
        canonical_avg = sum(canonical_scores) / len(canonical_scores)
        improvement = narrow_avg - canonical_avg
        improvement_percent = (improvement / narrow_avg * 100) if narrow_avg > 0 else 0

        results = {
            "narrow_avg_ai_detection": round(narrow_avg, 2),
            "canonical_avg_ai_detection": round(canonical_avg, 2),
            "improvement_points": round(improvement, 2),
            "improvement_percent": round(improvement_percent, 1),
            "success": improvement >= 5,  # Success if improvement >= 5 points
            "message": f"Quality gate improvement: {improvement:.1f} points ({improvement_percent:.1f}%)",
            "judge": "Claude Opus 5"
        }

        print(f"\n{'='*50}")
        print(f"Benchmark Results (Judged by Opus 5):")
        print(f"{'='*50}")
        print(f"Without rig (narrow):  {narrow_avg:.1f}/100 (AI-detectable)")
        print(f"With rig (canonical):  {canonical_avg:.1f}/100 (AI-detectable)")
        print(f"Improvement:           {improvement:.1f} points ({improvement_percent:.1f}%)")
        print(f"Status:                {'PASS ✓' if results['success'] else 'FAIL ✗'}")
    else:
        results = {"success": False, "message": "Failed to load implementations"}

    print(f"\n{json.dumps(results, indent=2)}")
    sys.exit(0 if results.get("success", False) else 1)


if __name__ == "__main__":
    main()
